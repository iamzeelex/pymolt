from __future__ import annotations

import re

from typer.testing import CliRunner

from pymolt.assess.service import write_target_manifest
from pymolt.core.enums import Mode, Provenance, ResolutionQuality, SourceFixation
from pymolt.core.graph import DependencyGraph, Node
from pymolt.core.layers import IngestionReport
from pymolt.delta.envs import uv_failure
from pymolt.setup.baseline_hint import build_baseline_hint


def _graph():
    node = Node(name="six", version="1.16.0", mode=Mode.PYPI, provenance=Provenance.PYPI,
                direct=True)
    return DependencyGraph(nodes={"six": node}, resolution_quality=ResolutionQuality.RESOLVED,
                           source_fixation=SourceFixation.PINNED)


def test_the_target_manifest_names_the_command_that_wrote_it(tmp_path):
    written = write_target_manifest(tmp_path, _graph(), "uv", "3.12", with_hashes=False)
    assert written.read_text().splitlines()[0] == "# Generated by pymolt assess for Python 3.12"


def test_the_legacy_hint_reruns_assess_with_a_visible_option(tmp_path):
    from pymolt.interfaces.cli.commands import app

    hint = build_baseline_hint(tmp_path, "3.6")
    assert "--base-python 3.6" in hint.rerun_command
    assert "--current-python" not in hint.rerun_command + hint.agent_brief

    import typer

    assess = typer.main.get_command(app).commands["assess"]
    visible = {opt for p in assess.params if not getattr(p, "hidden", False) for opt in p.opts}
    assert "--base-python" in visible


def test_a_python_read_from_the_project_is_not_called_cached(tmp_path, monkeypatch):
    from pymolt.interfaces.cli import commands

    (tmp_path / "requirements.txt").write_text("six==1.16.0\n")
    (tmp_path / ".python-version").write_text("3.6.1\n")
    report = IngestionReport(resolution_quality="resolved", source_fixation="pinned",
                             manual_zone=[], warnings=[], detected_python="3.6.1")
    monkeypatch.setattr(commands, "_resolve_baseline_graph",
                        lambda **k: (_graph(), report, None))
    monkeypatch.setattr(commands, "_resolve_target_graph", lambda *a, **k: (_graph(), None))
    monkeypatch.setattr(commands, "get_eol_versions", lambda: {})
    monkeypatch.setattr("sys.stdout.isatty", lambda: False)

    result = CliRunner().invoke(commands.app, ["assess", str(tmp_path), "--target-python",
                                               "3.12", "--no-write"])

    assert "3.6.1 (project config)" in result.output
    assert "cached config" not in result.output


def test_a_git_warning_is_printed_once_per_package(tmp_path):
    from pymolt.interfaces.cli.commands import app

    url = "git+git://github.com/blaze/odo.git"
    (tmp_path / "requirements.txt").write_text(f"{url}\n-e git://github.com/x/dshape.git#egg=dshape\n")
    (tmp_path / "requirements-dev.txt").write_text(f"{url}\n-e git://github.com/x/dshape.git#egg=dshape\n")

    out = CliRunner().invoke(app, ["scan", str(tmp_path)], env={"COLUMNS": "200"}).output
    out = re.sub(r"\x1b\[[0-9;?]*[A-Za-z]", "", out)     # CI forces colour

    warnings = [line for line in out.splitlines() if "git:// protocol was disabled" in line]
    assert len(warnings) == 2, warnings
    assert any("odo:" in w and "(2 lines)" in w for w in warnings)
    assert any("dshape:" in w for w in warnings)


def test_uvs_wrapped_failure_stays_readable():
    stderr = (
        "  \x1b[31m×\x1b[0m No solution found when resolving dependencies:\n"
        "  ╰─▶ Because certifi was not found in the cache and requests==2.32.3\n"
        "      (v2.34.2) depends on certifi>=2017.4.17, we can conclude that\n"
        "      requests==2.32.3 cannot be used.\n"
        "      hint: Packages were unavailable because the network was disabled.\n"
    )
    message = uv_failure(stderr)
    assert message == (
        "No solution found when resolving dependencies: Because certifi was not found in "
        "the cache and requests==2.32.3 (v2.34.2) depends on certifi>=2017.4.17, we can "
        "conclude that requests==2.32.3 cannot be used.")
    assert uv_failure("error: Failed to download `x==1`\n  Caused by: Network is disabled\n") \
        == "Failed to download `x==1`: Network is disabled"
