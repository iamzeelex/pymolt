"""A pip-compile output read as the manifest (QA I7, zipline).

zipline's ``etc/requirements_py36_locked.txt`` gave ``declared_constraint: "==1.11.8  # via
-r etc/requirements.in"`` on all 97 rows, every one marked direct; and a fully pinned
manifest read declared-only printed "After resolution: intent" beside "GOLD ... Pinned".
"""

from __future__ import annotations

from pymolt.assess.service import extract_constraint
from pymolt.ingestion.detect import compiled_transitive, extract_declared_requirements
from pymolt.ingestion.orchestrator import orchestrate_ingestion

INLINE = """#
# This file is autogenerated by pip-compile
#
-e git+git://github.com/quantopian/blaze.git@f26375a6#egg=blaze  # via -r etc/requirements_blaze.in
alembic==0.7.7            # via -r etc/requirements.in
certifi==2018.8.24        # via requests
click==7.0.0              # via -r etc/requirements.in, flask, pip-tools
contextlib2==0.6.0.post1 ; python_version < "3.0"  # via -r etc/requirements.in, blaze
requests==2.20.1          # via -r etc/requirements.in
"""
BLOCKS = """certifi==2024.2.2 \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via requests
idna==3.6
    # via
    #   anyio
    #   requests
requests==2.31.0
    # via -r requirements.in
"""


def test_inline_comments_are_not_part_of_the_requirement(tmp_path):
    lock = tmp_path / "requirements_locked.txt"
    lock.write_text(INLINE)

    declared = extract_declared_requirements(lock)

    assert declared["alembic"] == "alembic==0.7.7"
    assert declared["contextlib2"] == 'contextlib2==0.6.0.post1 ; python_version < "3.0"'
    assert extract_constraint(declared["certifi"]) == "==2018.8.24"


def test_via_comments_tell_transitive_from_declared(tmp_path):
    inline = tmp_path / "requirements_locked.txt"
    inline.write_text(INLINE)
    blocks = tmp_path / "requirements.txt"
    blocks.write_text(BLOCKS)
    plain = tmp_path / "requirements-plain.txt"
    plain.write_text("flask==2.0.3\nsix==1.16.0\n")

    assert compiled_transitive(inline) == {"certifi"}
    assert compiled_transitive(blocks) == {"certifi", "idna"}
    assert compiled_transitive(plain) == set()          # no provenance: all declared


def test_a_compiled_manifest_read_declared_only_is_pinned_and_keeps_provenance(
        tmp_path, monkeypatch):
    from pymolt.ingestion import fallback_compiler

    def no_interpreter(*a, **k):
        raise ValueError("Python 3.6 interpreter was not found")

    monkeypatch.setattr(fallback_compiler, "compile_legacy", no_interpreter)
    (tmp_path / "requirements_locked.txt").write_text(INLINE.replace(
        '-e git+git://github.com/quantopian/blaze.git@f26375a6#egg=blaze  # via -r etc/'
        'requirements_blaze.in\n', ""))

    graph, report = orchestrate_ingestion(tmp_path, base_python="3.6", use_cache=False)

    assert report.resolution_quality == "declared-only"
    assert report.source_fixation == "pinned"            # what the declarations pin
    assert graph.nodes["certifi"].direct is False
    assert graph.nodes["alembic"].direct is True
    assert "certifi" not in graph.roots and "alembic" in graph.roots
    assert all("#" not in (n.declared_requirement or "") for n in graph.nodes.values())
